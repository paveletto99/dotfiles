#!/usr/bin/env python3
"""Deploy explicit dotfile links with reversible backups; Python 3.11+ required."""

import argparse
import copy
import datetime
import json
import os
from pathlib import Path
import shutil
import sys
import tempfile
import tomllib


def merge_codex_settings(base, local):
    """Keep host integration overrides while sharing portable Codex settings."""
    result = copy.deepcopy(base)
    for key, value in local.items():
        if isinstance(value, dict) and isinstance(result.get(key), dict):
            result[key] = merge_codex_settings(result[key], value)
        else:
            result[key] = copy.deepcopy(value)
    return result


def render_toml_settings(settings):
    """Serialize supported configuration values without third-party dependencies."""
    def literal(value):
        if isinstance(value, str):
            return json.dumps(value, ensure_ascii=False)
        if isinstance(value, bool):
            return str(value).lower()
        if isinstance(value, (int, float)):
            return repr(value)
        if isinstance(value, list):
            return "[" + ", ".join(literal(item) for item in value) + "]"
        if isinstance(value, dict):
            return "{ " + ", ".join(
                f"{json.dumps(key)} = {literal(item)}" for key, item in value.items()
            ) + " }"
        raise ValueError(f"Unsupported TOML value type: {type(value).__name__}")

    lines = ["# Generated by dotfiles; edit .codex/config.toml or local/codex.toml."]

    def table(values, parents=()):
        if parents:
            lines.extend(["", "[" + ".".join(json.dumps(p) for p in parents) + "]"])
        for key, value in values.items():
            if not isinstance(value, dict):
                lines.append(f"{json.dumps(key)} = {literal(value)}")
        for key, value in values.items():
            if isinstance(value, dict):
                table(value, (*parents, key))

    table(settings)
    rendered = "\n".join(lines) + "\n"
    if tomllib.loads(rendered) != settings:
        raise ValueError("Codex configuration failed TOML round-trip validation")
    return rendered


def managed_dotfile_links(root, platform):
    """List managed files without folding runtime directories into repository links."""
    links = [(name, name) for name in (".zshenv", ".zprofile", ".zshrc", ".gitconfig")]
    for name in (
        "starship.toml", "herdr/config.toml", "btop/btop.conf", "htop/htoprc",
        "ripgrep/config", "git/ignore", "zed/settings.json", "nvim",
    ):
        links.append((f".config/{name}", f".config/{name}"))
    links.extend([
        (".config/ghostty/config.ghostty", ".config/ghostty/config.ghostty"),
        (".codex/AGENTS.md", ".codex/AGENTS.md"),
    ])
    editor_target = (
        "Library/Application Support/Code - Insiders/User/settings.json"
        if platform == "darwin" else ".config/Code - Insiders/User/settings.json"
    )
    links.append((".config/vscode/settings.json", editor_target))
    for folder in (".agents/skills", ".codex/skills"):
        for skill in sorted((root / folder).iterdir()):
            if skill.is_dir() and not skill.name.startswith("."):
                links.append((f"{folder}/{skill.name}", f"{folder}/{skill.name}"))
    if (root / "local/zshrc.local").is_file():
        links.append(("local/zshrc.local", ".zshrc.local"))
    return links


class DotfileDeployment:
    """Back up conflicts before replacing only explicitly managed files."""
    def __init__(self, root, home, platform, mode):
        self.root, self.home, self.platform, self.mode = root, home, platform, mode
        self.backup_root = None
        self.operations = []
        self.drift = []

    def backup(self, target):
        if not os.path.lexists(target):
            return
        if self.backup_root is None:
            stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S-%f")
            self.backup_root = self.home / ".local/state/dotfiles/backups" / stamp
            self.backup_root.mkdir(parents=True, mode=0o700)
        saved = self.backup_root / target.relative_to(self.home)
        saved.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(target), str(saved))
        self.operations.append({"target": str(target), "backup": str(saved)})
        # Save each operation immediately, so interrupted deployment is recoverable.
        (self.backup_root / "manifest.json").write_text(json.dumps(self.operations, indent=2) + "\n")

    def report_change(self, target):
        self.drift.append(str(target.relative_to(self.home)))
        print(f"{'DRIFT' if self.mode == 'check' else 'MANAGE'} {target}")

    def link(self, source, target):
        if not source.exists():
            raise ValueError(f"Managed dotfile source missing: {source}")
        if target.is_symlink() and target.resolve() == source.resolve():
            return
        self.report_change(target)
        if self.mode != "apply":
            return
        self.backup(target)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.symlink_to(source, target_is_directory=source.is_dir())

    def write_codex(self):
        base = tomllib.loads((self.root / ".codex/config.toml").read_text())
        host_file = self.root / "local/codex.toml"
        local = tomllib.loads(host_file.read_text()) if host_file.exists() else {}
        settings = merge_codex_settings(base, local)
        target = self.home / ".codex/config.toml"
        rendered = render_toml_settings(settings)
        if target.is_file():
            try:
                if tomllib.loads(target.read_text()) == settings:
                    return
            except tomllib.TOMLDecodeError:
                pass
        self.report_change(target)
        if self.mode != "apply":
            return
        self.backup(target)
        target.parent.mkdir(parents=True, exist_ok=True)
        descriptor, temporary = tempfile.mkstemp(dir=target.parent, prefix=".dotfiles-")
        try:
            with os.fdopen(descriptor, "w") as handle:
                handle.write(rendered)
            os.chmod(temporary, 0o600)
            os.replace(temporary, target)
        finally:
            if os.path.exists(temporary):
                os.unlink(temporary)

    def remove_override(self, target):
        if not os.path.lexists(target):
            return
        # Multiple aliases of the same Ghostty file can duplicate repeatable keys.
        self.report_change(target)
        if self.mode == "apply":
            self.backup(target)

    def deploy(self):
        links = managed_dotfile_links(self.root, self.platform)
        # Validate every source and the rendered configuration before changing files.
        for source, relative_target in links:
            if not (self.root / source).exists():
                raise ValueError(f"Managed dotfile source missing: {source}")
            parent = (self.home / relative_target).parent
            while parent != self.home:
                if parent.is_symlink():
                    raise ValueError(f"Managed dotfile parent is a symlink; review before deployment: {parent}")
                parent = parent.parent
        host = self.root / "local/codex.toml"
        render_toml_settings(merge_codex_settings(
            tomllib.loads((self.root / ".codex/config.toml").read_text()),
            tomllib.loads(host.read_text()) if host.exists() else {},
        ))
        for source, target in links:
            self.link(self.root / source, self.home / target)
        overrides = [".config/ghostty/config"]
        if self.platform == "darwin":
            overrides.extend([
                "Library/Application Support/com.mitchellh.ghostty/config",
                "Library/Application Support/com.mitchellh.ghostty/config.ghostty",
            ])
        for target in overrides:
            self.remove_override(self.home / target)
        self.write_codex()
        if self.backup_root:
            print(f"Backups: {self.backup_root}")
        if not self.drift:
            print("Managed configuration matches the repository.")
        return 1 if self.mode == "check" and self.drift else 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--home", type=Path, default=Path.home())
    parser.add_argument("--platform", choices=["darwin", "linux"], default=sys.platform)
    parser.add_argument("--mode", choices=["apply", "check", "dry-run"], default="check")
    args = parser.parse_args()
    if args.home.resolve() == args.root.resolve():
        parser.error("Deployment home must differ from the repository")
    try:
        return DotfileDeployment(args.root.resolve(), args.home.absolute(), args.platform, args.mode).deploy()
    except (OSError, ValueError) as error:
        print(f"Dotfile deployment failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
